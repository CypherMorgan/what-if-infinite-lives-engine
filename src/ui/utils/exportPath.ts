/**
 * Export the selected path as a Markdown report.
 */
import type { SimulationDoc } from '../../core/types';
import { pathTo } from '../../core/engine';
import { formatValue } from '../../core/vars';
import { APP_VERSION } from '../../core/importExport';

export function exportPathAsMarkdown(doc: SimulationDoc, nodeId: string): string {
  const path = pathTo(doc, nodeId);
  const lines: string[] = [];

  lines.push(`# Path Report: ${doc.title}`);
  lines.push('');
  lines.push(`**Generated:** ${new Date().toISOString()}`);
  lines.push(`**Selected node:** ${doc.nodes[nodeId]?.title ?? nodeId}`);
  lines.push(`**Path length:** ${path.length} nodes`);
  lines.push('');
  lines.push('## Timeline');
  lines.push('');

  for (let i = 0; i < path.length; i++) {
    const id = path[i]!;
    const node = doc.nodes[id];
    if (!node) continue;
    const branch = doc.branches[node.branch];
    lines.push(`### ${i + 1}. ${node.title} (${node.horizon}, t=${node.t} mo)`);
    lines.push(`**Branch:** ${branch?.name ?? node.branch} | **Type:** ${node.type}`);
    lines.push('');
    lines.push(node.summary);
    lines.push('');

    if (node.detail) {
      lines.push(node.detail);
      lines.push('');
    }

    if (node.tradeoffs) {
      if (node.tradeoffs.gains.length > 0) {
        lines.push('**Gains:**');
        for (const g of node.tradeoffs.gains) lines.push(`- ${g}`);
        lines.push('');
      }
      if (node.tradeoffs.costs.length > 0) {
        lines.push('**Costs:**');
        for (const c of node.tradeoffs.costs) lines.push(`- ${c}`);
        lines.push('');
      }
    }

    if (node.state) {
      lines.push('**State snapshot:**');
      const keys = Object.keys(node.state).slice(0, 12);
      for (const k of keys) {
        const def = doc.vars.find((v) => v.key === k);
        const val = node.state[k];
        if (val === undefined) continue;
        lines.push(`- ${def?.label ?? k}: ${formatValue(val, def?.unit ?? 'index')}`);
      }
      lines.push('');
    }

    if (node.nextSteps && node.nextSteps.length > 0) {
      lines.push('**Next steps:**');
      for (const s of node.nextSteps) lines.push(`- ${s}`);
      lines.push('');
    }

    if (node.failurePoints && node.failurePoints.length > 0) {
      lines.push('**Failure points:**');
      for (const f of node.failurePoints) lines.push(`- ${f}`);
      lines.push('');
    }

    if (node.userNotes) {
      lines.push('**Notes:**');
      lines.push(node.userNotes);
      lines.push('');
    }

    lines.push('---');
    lines.push('');
  }

  lines.push('## Assumptions');
  lines.push('');
  for (const a of doc.assumptions) {
    lines.push(
      `- **${a.label}** (${a.varKey}): ${formatValue(a.value, a.unit)} (base: ${formatValue(a.baseValue, a.unit)}) — ${a.rationale}`
    );
  }
  lines.push('');
  lines.push(`*Generated by What If? — The Infinite Lives Engine v${APP_VERSION}*`);

  return lines.join('\n');
}

export function downloadMarkdown(content: string, filename: string): void {
  try {
    const blob = new Blob([content], { type: 'text/markdown;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = filename.replace(/\.json$/i, '') + '-path.md';
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  } catch (err) {
    console.error('Failed to download markdown:', err);
    throw err;
  }
}
