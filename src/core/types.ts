/**
 * Domain model for a simulation ("universe").
 *
 * This is the single integration contract between the engine, the AI layer, persistence and
 * the UI. Everything persisted is expressed here; the schema version drives migrations.
 */

export type NodeId = string;
export type EdgeId = string;
export type BranchId = string;
export type SimId = string;

/** Bumped when a persisted shape changes in a way that needs data migration. */
export const SCHEMA_VERSION = 3;

// ---------------------------------------------------------------------------
// Evidence classification — the honesty backbone of the app.
// ---------------------------------------------------------------------------

/**
 * How much weight a statement deserves. Every user-visible claim in a node carries one of
 * these so the UI can render "you told me this" differently from "the model invented this".
 */
export type EvidenceClass =
  | 'user-fact' // the user stated this; treated as a given
  | 'research' // grounded in an external reference the pack cites
  | 'assumption' // a modelling assumption, stated and editable
  | 'speculation'; // imaginative extrapolation, clearly not a prediction

export interface EvidenceTag {
  cls: EvidenceClass;
  text: string;
  /** Optional citation for `research` tags. */
  source?: string;
}

export const EVIDENCE_LABEL: Record<EvidenceClass, string> = {
  'user-fact': 'You told us',
  research: 'Referenced',
  assumption: 'Assumption',
  speculation: 'Speculation',
};

// ---------------------------------------------------------------------------
// State vector
// ---------------------------------------------------------------------------

export type StateVector = Record<string, number>;

export type VarUnit = 'currency' | 'months' | 'percent' | 'count' | 'level' | 'index';
export type VarKind =
  | 'resource'
  | 'capacity'
  | 'skill'
  | 'risk'
  | 'progress'
  | 'relationship'
  | 'market';
export type VarDirection = 'up' | 'down' | 'neutral';
export type VarDomain =
  | 'financial'
  | 'career'
  | 'personal'
  | 'health'
  | 'social'
  | 'project'
  | 'learning';

export interface VarDef {
  key: string;
  label: string;
  unit: VarUnit;
  kind: VarKind;
  /** Which direction is "good" — drives colour and comparison semantics. */
  direction: VarDirection;
  domain: VarDomain;
  /** Show by default in the state readout. */
  primary?: boolean;
  /** One-line explanation shown in tooltips. */
  hint?: string;
}

// ---------------------------------------------------------------------------
// Nodes
// ---------------------------------------------------------------------------

export type NodeType =
  | 'start'
  | 'decision'
  | 'event'
  | 'opportunity'
  | 'setback'
  | 'milestone'
  | 'consequence'
  | 'alternative'
  | 'ending';

export const NODE_TYPE_LABEL: Record<NodeType, string> = {
  start: 'Starting state',
  decision: 'Decision',
  event: 'Event',
  opportunity: 'Opportunity',
  setback: 'Setback',
  milestone: 'Milestone',
  consequence: 'Consequence',
  alternative: 'Alternative outcome',
  ending: 'Future state',
};

export interface TradeOff {
  gains: string[];
  costs: string[];
}

/** A single change a node makes to the state vector, kept for explainability. */
export interface StateDelta {
  key: string;
  before: number;
  after: number;
  /** Human-readable cause, e.g. "6 months of living costs". */
  reason: string;
}

export interface DecisionOption {
  id: string;
  label: string;
  /** Where choosing this option leads, once expanded. */
  leadsTo?: NodeId;
}

export interface SimNode {
  id: NodeId;
  type: NodeType;
  title: string;
  /** 1–3 sentence summary shown on the node card. */
  summary: string;
  /** Long-form explanation shown in the inspector. */
  detail?: string;
  /** Months elapsed from the scenario's "now". */
  t: number;
  /** Human-readable time band, e.g. "6–18 months". */
  horizon: string;
  branch: BranchId;
  depth: number;
  parents: NodeId[];
  children: NodeId[];
  assumptions: string[];
  uncertainties: string[];
  evidence: EvidenceTag[];
  tradeoffs?: TradeOff;
  decision?: { question: string; options: DecisionOption[] };
  /** State after this node's transition. Absent on the start node's predecessors. */
  state?: StateVector;
  /** What this node changed, for the "why this path?" explanation. */
  delta?: StateDelta[];
  /** Plausible metrics computed from state, not invented. */
  nextSteps?: string[];
  failurePoints?: string[];
  resources?: string[];
  /** Whether children can be generated for this node. */
  expandable: boolean;
  /** Whether children have been generated already. */
  expanded: boolean;
  /** Rule id that produced this node, when generated by the simulation engine. */
  ruleId?: string;
}

export type EdgeKind = 'causal' | 'choice' | 'alternative' | 'consequence';

export interface SimEdge {
  id: EdgeId;
  from: NodeId;
  to: NodeId;
  kind: EdgeKind;
  label?: string;
  /** How strongly the causal hypothesis is supported. */
  confidence: 'high' | 'medium' | 'low';
  hypothesis: string;
}

// ---------------------------------------------------------------------------
// Branches
// ---------------------------------------------------------------------------

export interface Branch {
  id: BranchId;
  name: string;
  /** Hue in degrees; the renderer derives the full palette from this. */
  hue: number;
  /** Node the branch originates from. */
  root: NodeId;
  description: string;
}

// ---------------------------------------------------------------------------
// Assumptions (editable, the basis of counterfactuals)
// ---------------------------------------------------------------------------

export interface Assumption {
  id: string;
  label: string;
  /** Which state key this assumption seeds. */
  varKey: string;
  unit: VarUnit;
  /** The value the original scenario was built with. */
  baseValue: number;
  /** The value currently in force in this version. */
  value: number;
  rationale: string;
  /** 0–1, model-derived influence on headline outcomes. Drives sensitivity display. */
  sensitivity: number;
  /** User-editable from the UI. */
  editable: boolean;
}

// ---------------------------------------------------------------------------
// Scenario prompt
// ---------------------------------------------------------------------------

export interface ScenarioPrompt {
  situation: string;
  decision: string;
  goals: string[];
  constraints: string[];
  /** Months. */
  horizon: number;
  /** How many top-level branches to create initially. */
  branchCount: number;
  /** 0 = grounded analysis, 1 = imaginative exploration. */
  imagination: number;
  resources: string[];
  /** Detected archetype ids used to select rule packs. */
  archetypes: string[];
  /** Scenario title, usually derived from the decision. */
  title: string;
}

// ---------------------------------------------------------------------------
// Counterfactual lineage
// ---------------------------------------------------------------------------

export interface Counterfactual {
  /** Assumption or decision that was changed. */
  target: string;
  fromValue: string;
  toValue: string;
  note: string;
  createdAt: string;
}

// ---------------------------------------------------------------------------
// The simulation document
// ---------------------------------------------------------------------------

export interface LayoutPoint {
  x: number;
  y: number;
}

export interface SimulationMeta {
  generator: 'offline' | 'ai';
  providerLabel: string;
  modelLabel?: string;
  /** Free-form note about how this universe was produced. */
  provenance: string;
}

export interface SimulationDoc {
  id: SimId;
  schemaVersion: number;
  createdAt: string;
  updatedAt: string;
  title: string;
  prompt: ScenarioPrompt;
  seed: number;
  nodes: Record<NodeId, SimNode>;
  edges: Record<EdgeId, SimEdge>;
  branches: Record<BranchId, Branch>;
  layout: Record<NodeId, LayoutPoint>;
  vars: VarDef[];
  assumptions: Assumption[];
  /** Collapsed branches, hidden from the canvas. */
  collapsed: BranchId[];
  meta: SimulationMeta;
  /** Set when this document was derived from another by changing something. */
  parentId?: SimId;
  counterfactual?: Counterfactual;
  /** The node the user last focused, restored on reopen. */
  focusNode?: NodeId;
  /** Camera saved with the layout so reopening restores the user's view. */
  camera?: { x: number; y: number; scale: number };
}

/** Lightweight index entry for the library screen — avoids loading whole documents. */
export interface SimulationSummary {
  id: SimId;
  title: string;
  createdAt: string;
  updatedAt: string;
  nodeCount: number;
  branchCount: number;
  generator: SimulationMeta['generator'];
  parentId?: string;
  isCounterfactual: boolean;
}

// ---------------------------------------------------------------------------
// Lookup helpers (records are keyed maps; `noUncheckedIndexedAccess` is on)
// ---------------------------------------------------------------------------

export function nodeById(doc: SimulationDoc, id: NodeId): SimNode | undefined {
  return doc.nodes[id];
}

export function requireNode(doc: SimulationDoc, id: NodeId): SimNode {
  const n = doc.nodes[id];
  if (!n) throw new Error(`Graph integrity error: node "${id}" does not exist.`);
  return n;
}

export function branchById(doc: SimulationDoc, id: BranchId): Branch | undefined {
  return doc.branches[id];
}

export function nodeList(doc: SimulationDoc): SimNode[] {
  return Object.values(doc.nodes);
}

export function edgeList(doc: SimulationDoc): SimEdge[] {
  return Object.values(doc.edges);
}
